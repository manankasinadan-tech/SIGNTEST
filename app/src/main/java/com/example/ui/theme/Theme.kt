@Immutable
data class SemanticColors(
    val verified: Color,
    val verifiedContainer: Color,
    val warning: Color,
    val warningContainer: Color,
    val codeSurface: Color
)

val LocalSemanticColors = staticCompositionLocalOf {
    SemanticColors(
        verified = VerifiedGreenLight,
        verifiedContainer = VerifiedGreenBgLight,
        warning = WarningAmberLight,
        warningContainer = WarningAmberBgLight,
        codeSurface = LightSurfaceVariant
    )
}

