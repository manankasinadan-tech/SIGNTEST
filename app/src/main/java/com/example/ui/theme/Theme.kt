private val AppShapes = Shapes(
    extraSmall = RoundedCornerShape(6.dp),
    small = RoundedCornerShape(10.dp),
    medium = RoundedCornerShape(14.dp),
    large = RoundedCornerShape(18.dp),
    extraLarge = RoundedCornerShape(24.dp)
)

@Composable
fun SignerLabTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    val semanticColors = if (darkTheme) {
        SemanticColors(
            verified = VerifiedGreenDark,
            verifiedContainer = VerifiedGreenBgDark,
            warning = WarningAmberDark,
            warningContainer = WarningAmberBgDark,
            codeSurface = DarkSurfaceVariant
        )
    } else {
        SemanticColors(
            verified = VerifiedGreenLight,
            verifiedContainer = VerifiedGreenBgLight,
            warning = WarningAmberLight,
            warningContainer = WarningAmberBgLight,
            codeSurface = LightSurfaceVariant
        )
    }

    CompositionLocalProvider(LocalSemanticColors provides semanticColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = AppTypography,
            shapes = AppShapes,
            content = content
        )
    }
}
